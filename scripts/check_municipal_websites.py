"""Check what municipal websites show about activities and seniors (online visibility).

Usage (from the repository root):

    python scripts/check_municipal_websites.py data/raw/opendata_gencat/ajuntaments_baix_emporda.json

For each municipality (official website from the Generalitat's local-authority
register), the script:
  1. requests the homepage once;
  2. records links whose URL or text points to an activities agenda, or to
     seniors / casals (keyword lists below);
  3. if an agenda link is found, requests that page once and counts senior
     keywords in its visible text.

It stores observations only (no page copies) in
data/raw/web_checks/municipal_websites_<comarca>_<date>.json, one record per
municipality with the URLs found, HTTP status and timestamps.

Limitations (documented in notebook 05): only the homepage and one agenda page
are read; links generated by JavaScript or hidden in menus loaded later are
missed; a site that blocks automated requests is recorded as not checked. A
missing link therefore does NOT mean the municipality has no agenda or no
senior activities.
"""
from __future__ import annotations

import html
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "data" / "raw" / "web_checks"
USER_AGENT = "Mozilla/5.0 (compatible; academic-research-bot; TFG UPF)"
PAUSE_SECONDS = 1.5

AGENDA = re.compile(r"agenda|programaci[oó]|esdeveniments|calendari", re.I)
SENIOR = re.compile(r"gent[\s_-]*gran|casal[\s_-]*(d[\s_'’-]*)?avis|jubilat|s[eè]nior|llar[\s_-]*del[\s_-]*jubilat|envelliment|persones[\s_-]*grans", re.I)
SENIOR_TEXT = re.compile(r"gent gran|casal d['’]avis|jubilat|s[eè]nior|persones grans|majors de (60|65)", re.I)


def get(url: str) -> tuple[int | None, str, str]:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept-Language": "ca,es;q=0.8"})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.status, r.geturl(), r.read(3_000_000).decode("utf-8", "replace")
    except urllib.error.HTTPError as e:
        return e.code, url, ""
    except Exception as e:  # network errors, timeouts, TLS
        return None, url, f"ERROR: {type(e).__name__}: {e}"


def links(page: str, base: str) -> list[tuple[str, str]]:
    out = []
    for href, text in re.findall(r'<a\b[^>]*href=["\']([^"\'#]+)["\'][^>]*>(.*?)</a>', page, flags=re.S | re.I):
        text = re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", text))).strip()
        out.append((urllib.parse.urljoin(base, html.unescape(href)), text[:80]))
    return out


def visible_text(page: str) -> str:
    page = re.sub(r"<(script|style)\b.*?</\1>", " ", page, flags=re.S | re.I)
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", page)))


def check(municipality: dict) -> dict:
    url = municipality["web"].strip()
    if not url.startswith("http"):
        url = "http://" + url
    rec = dict(codi_municipi=municipality["codi_municipi"], municipi=municipality["municipi"],
               website=url, checked_utc=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"))
    status, final, page = get(url)
    attempts = 1
    # One retry for transient failures, then the https variant of the address
    for retry_url in (url, url.replace("http://", "https://", 1)):
        if status == 200 and not page.startswith("ERROR"):
            break
        time.sleep(3)
        status, final, page = get(retry_url)
        attempts += 1
    rec["home_attempts"] = attempts
    rec.update(home_status=status, home_final_url=final, home_bytes=len(page),
               home_error=page if page.startswith("ERROR") else "")
    if status != 200 or page.startswith("ERROR"):
        return rec
    ls = links(page, final)
    agenda = [(u, t) for u, t in ls if AGENDA.search(u) or AGENDA.search(t)]
    senior = [(u, t) for u, t in ls if SENIOR.search(u) or SENIOR.search(t)]
    rec["agenda_links"] = sorted({u for u, _ in agenda})[:10]
    rec["senior_links"] = sorted({u for u, _ in senior})[:10]
    rec["senior_terms_on_home"] = len(SENIOR_TEXT.findall(visible_text(page)))
    if agenda:
        # prefer a link whose URL contains 'agenda'
        first = sorted({u for u, _ in agenda}, key=lambda u: (0 if "agenda" in u.lower() else 1, len(u)))[0]
        time.sleep(PAUSE_SECONDS)
        a_status, a_final, a_page = get(first)
        rec.update(agenda_checked_url=first, agenda_status=a_status, agenda_bytes=len(a_page))
        if a_status == 200 and not a_page.startswith("ERROR"):
            rec["senior_terms_on_agenda"] = len(SENIOR_TEXT.findall(visible_text(a_page)))
    return rec


def main() -> int:
    source = Path(sys.argv[1])
    municipalities = json.loads(source.read_text(encoding="utf-8"))
    comarca = municipalities[0]["comarca"].lower().replace(" ", "_").replace("à", "a")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    results = []
    for m in municipalities:
        results.append(check(m))
        r = results[-1]
        print(f"{m['municipi']:45s} home={r.get('home_status')} agenda={len(r.get('agenda_links', []))} "
              f"senior={len(r.get('senior_links', []))} agenda_page_senior_terms={r.get('senior_terms_on_agenda')}")
        time.sleep(PAUSE_SECONDS)
    out = OUT_DIR / f"municipal_websites_{comarca}_{datetime.now(timezone.utc):%Y-%m-%d}.json"
    out.write_text(json.dumps(dict(source=str(source.resolve().relative_to(ROOT)), user_agent=USER_AGENT,
                                   agenda_pattern=AGENDA.pattern, senior_link_pattern=SENIOR.pattern,
                                   senior_text_pattern=SENIOR_TEXT.pattern, results=results),
                              ensure_ascii=False, indent=1), encoding="utf-8")
    print("saved", out.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
